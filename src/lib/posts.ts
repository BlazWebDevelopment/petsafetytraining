export function getAllPosts(): Post[] {
  return [...POSTS].sort((a, b) => b.date.localeCompare(a.date))
}

export function getPostById(id: string): Post | undefined {
  return POSTS.find((p) => p.id === id)
}

export function getPostsByCategory(categoryId: string): Post[] {
  return getAllPosts().filter((p) =>
    p.categories.some((c) => c.id === categoryId),
  )
}

export function getCategoryById(id: string): Category | undefined {
  return CATEGORIES.find((c) => c.id === id)
}

/** Adjacent posts in reverse-chronological order, for the prev/next footer nav. */
export function getAdjacentPosts(id: string): {
  newer?: Post
  older?: Post
} {
  const all = getAllPosts()
  const i = all.findIndex((p) => p.id === id)
  if (i === -1) return {}
  return { newer: all[i - 1], older: all[i + 1] }
}

/** Excerpt used on the index page, mirroring livedoor's truncated preview. */
export function getExcerpt(post: Post, length = 110): string {
  const flat = post.body.join('')
  return flat.length > length ? flat.slice(0, length) : flat
}

export function getMonthlyArchives(): {
  key: string
  label: string
  count: number
}[] {
  const map = new Map<string, number>()
  for (const p of getAllPosts()) {
    const key = p.date.slice(0, 7)
    map.set(key, (map.get(key) ?? 0) + 1)
  }
  return [...map.entries()]
    .sort((a, b) => b[0].localeCompare(a[0]))
    .map(([key, count]) => {
      const [y, m] = key.split('-')
      return { key, label: `${y}年${Number(m)}月`, count }
    })
}

export function getCategoryCounts(): { category: Category; count: number }[] {
  return CATEGORIES.map((category) => ({
    category,
    count: getPostsByCategory(category.id).length,
  })).filter((c) => c.count > 0)
}
